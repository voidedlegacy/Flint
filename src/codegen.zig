//! Emits textual LLVM IR. Every Flint function becomes
//!     define <ret> @flint.<name>(<ty> %p.arg, ...)
//! and a small C-compatible @main calls @flint.main and returns its result
//! as the process exit code.
//!
//! Each variable gets a stack slot (alloca). Reads are loads, writes are
//! stores. LLVM's mem2reg pass turns the slots into registers, so -O2
//! output is as tight as hand-written code.
//!
//!   define i64 @flint.f(i64 %a.arg) {
//!   entry:
//!     %a.0 = alloca i64        <- `allocas` buffer (all slots first)
//!     store i64 %a.arg, ...    <- `body` buffer
//!     ...
//!   }
const std = @import("std");
const ast = @import("ast.zig");
const Type = @import("types.zig").Type;
const Expr = ast.Expr;
const Stmt = ast.Stmt;

const Error = std.Io.Writer.Error || std.mem.Allocator.Error;

pub const CodeGen = struct {
    arena: std.mem.Allocator,
    allocas: std.Io.Writer.Allocating, // stack slots, at the top of the entry block
    body: std.Io.Writer.Allocating, // all other instructions
    ret_type: *const Type = undefined, // return type of the function being emitted
    next_tmp: u32 = 0,
    next_label: u32 = 0,
    terminated: bool = false, // the current block already ended with br/ret
    slots: std.AutoHashMapUnmanaged(*const ast.Var, []const u8) = .empty, // var -> its alloca
    slot_count: u32 = 0,
    loops: std.ArrayList(LoopLabels) = .empty, // innermost last, for break/continue

    const LoopLabels = struct {
        cond: []const u8, // continue jumps here
        end: []const u8, // break jumps here
    };

    pub fn init(arena: std.mem.Allocator) CodeGen {
        return .{ .arena = arena, .allocas = .init(arena), .body = .init(arena) };
    }

    /// Writes the whole module to `out`. There must be a `main`.
    pub fn run(self: *CodeGen, out: *std.Io.Writer, fns: []const *ast.FnDecl) Error!void {
        try out.writeAll("; generated by flint\n\n");
        var main_fn: ?*const ast.FnDecl = null;
        for (fns) |f| {
            try self.emitFn(out, f);
            if (std.mem.eql(u8, f.name, "main")) main_fn = f;
        }

        // The C entry point. `fn main()` exits with 0; `fn main() -> i64`
        // exits with its result.
        try out.writeAll("define i32 @main() {\nentry:\n");
        if (main_fn.?.ret_type.* == .void) {
            try out.writeAll("  call void @flint.main()\n  ret i32 0\n");
        } else {
            try out.writeAll("  %r = call i64 @flint.main()\n" ++
                "  %code = trunc i64 %r to i32\n" ++
                "  ret i32 %code\n");
        }
        try out.writeAll("}\n");
    }

    // ------------------------------------------------------------ helpers

    fn llvmType(t: *const Type) []const u8 {
        return switch (t.*) {
            .void => "void",
            .bool => "i1",
            .ref => "ptr",
            else => "i64",
        };
    }

    fn tmp(self: *CodeGen) Error![]const u8 {
        defer self.next_tmp += 1;
        return std.fmt.allocPrint(self.arena, "%t{d}", .{self.next_tmp});
    }

    fn line(self: *CodeGen, comptime fmt: []const u8, args: anytype) Error!void {
        try self.body.writer.print("  " ++ fmt ++ "\n", args);
    }

    /// Starts a new basic block. The previous one must already be terminated.
    fn label(self: *CodeGen, name: []const u8) Error!void {
        try self.body.writer.print("{s}:\n", .{name});
        self.terminated = false;
    }

    /// Ends the current block with a jump, unless it already returned.
    fn branchTo(self: *CodeGen, name: []const u8) Error!void {
        if (!self.terminated) try self.line("br label %{s}", .{name});
        self.terminated = true;
    }

    /// Gives `v` a uniquely named stack slot: shadowed variables share a
    /// Flint name, so the slot number keeps them apart.
    fn newSlot(self: *CodeGen, v: *const ast.Var) Error![]const u8 {
        const slot = try std.fmt.allocPrint(self.arena, "%{s}.{d}", .{ v.name, self.slot_count });
        self.slot_count += 1;
        try self.slots.put(self.arena, v, slot);
        try self.allocas.writer.print("  {s} = alloca {s}\n", .{ slot, llvmType(v.type) });
        return slot;
    }

    // ------------------------------------------------------------ functions

    fn emitFn(self: *CodeGen, out: *std.Io.Writer, f: *const ast.FnDecl) Error!void {
        self.allocas.clearRetainingCapacity();
        self.body.clearRetainingCapacity();
        self.slots.clearRetainingCapacity();
        self.slot_count = 0;
        self.loops.clearRetainingCapacity();
        self.next_tmp = 0;
        self.next_label = 0;
        self.terminated = false;
        self.ret_type = f.ret_type;

        // Parameters arrive as values (%a.arg). Copy each into a stack slot
        // so the body can treat it exactly like a local variable.
        var params: std.Io.Writer.Allocating = .init(self.arena);
        for (f.params, 0..) |p, i| {
            const ty = llvmType(p.type);
            const slot = try self.newSlot(p);
            if (i > 0) try params.writer.writeAll(", ");
            try params.writer.print("{s} %{s}.arg", .{ ty, p.name });
            try self.line("store {s} %{s}.arg, ptr {s}", .{ ty, p.name, slot });
        }

        try self.emitStmt(f.body);
        if (!self.terminated) {
            // A void function may fall off the end. A function with a return
            // type can't (the checker guarantees it), so the end is unreachable.
            try self.line("{s}", .{if (self.ret_type.* == .void) "ret void" else "unreachable"});
        }

        try out.print("define {s} @flint.{s}({s}) {{\nentry:\n", .{ llvmType(self.ret_type), f.name, params.written() });
        try out.writeAll(self.allocas.written());
        try out.writeAll(self.body.written());
        try out.writeAll("}\n\n");
    }

    // ------------------------------------------------------------ statements

    fn emitStmt(self: *CodeGen, s: *const Stmt) Error!void {
        if (self.terminated) {
            // Code after `return` is unreachable, but LLVM still needs every
            // instruction to live in a block. Open a fresh (dead) one.
            try self.body.writer.print("dead{d}:\n", .{self.next_label});
            self.next_label += 1;
            self.terminated = false;
        }

        switch (s.data) {
            .var_decl => |*v| {
                const slot = try self.newSlot(v);
                const value = try self.emitExpr(v.init.?);
                try self.line("store {s} {s}, ptr {s}", .{ llvmType(v.type), value, slot });
            },
            .assign => |as| {
                const value = try self.emitExpr(as.value);
                // The checker guarantees a variable or *p.
                const ptr = switch (as.target.data) {
                    .ident => |id| self.slots.get(id.decl.?).?, // x = e: x's slot
                    else => try self.emitExpr(as.target.data.unary.operand), // *p = e: p's value
                };
                try self.line("store {s} {s}, ptr {s}", .{ llvmType(as.target.type), value, ptr });
            },
            .ret => |value| {
                if (value) |e| {
                    const v = try self.emitExpr(e);
                    try self.line("ret {s} {s}", .{ llvmType(self.ret_type), v });
                } else {
                    try self.line("ret void", .{});
                }
                self.terminated = true;
            },
            .expr => |e| _ = try self.emitExpr(e), // result unused
            .for_ => |f| try self.emitFor(f),
            // The checker guarantees we are inside a loop.
            .break_ => try self.branchTo(self.loops.getLast().end),
            .continue_ => try self.branchTo(self.loops.getLast().cond),
            .if_ => |i| try self.emitIf(i),
            .block => |b| for (b.stmts) |child| try self.emitStmt(child),
        }
    }

    //           br %condN
    //   condN:  %c = ...
    //           br i1 %c, %bodyN, %endN
    //   bodyN:  ...
    //           br %condN          <- jump back: this is the loop
    //   endN:   (code after the loop)
    //
    //   Inside the body, `continue` is `br %condN` and `break` is `br %endN`.
    fn emitFor(self: *CodeGen, f: Stmt.For) Error!void {
        const n = self.next_label;
        self.next_label += 1;
        const cond_name = try std.fmt.allocPrint(self.arena, "cond{d}", .{n});
        const body_name = try std.fmt.allocPrint(self.arena, "body{d}", .{n});
        const end_name = try std.fmt.allocPrint(self.arena, "end{d}", .{n});

        try self.branchTo(cond_name);

        try self.label(cond_name);
        const cond = try self.emitExpr(f.cond);
        try self.line("br i1 {s}, label %{s}, label %{s}", .{ cond, body_name, end_name });
        self.terminated = true;

        try self.label(body_name);
        try self.loops.append(self.arena, .{ .cond = cond_name, .end = end_name });
        try self.emitStmt(f.body);
        _ = self.loops.pop();
        try self.branchTo(cond_name);

        try self.label(end_name);
    }

    //   entry:  %c = ...                   thenN:  ...
    //           br i1 %c, %thenN, %elseN           br %endN
    //                                      elseN:  ...
    //                                              br %endN
    //                                      endN:   (code after the if)
    fn emitIf(self: *CodeGen, i: Stmt.If) Error!void {
        const n = self.next_label;
        self.next_label += 1;
        const then_name = try std.fmt.allocPrint(self.arena, "then{d}", .{n});
        const else_name = try std.fmt.allocPrint(self.arena, "else{d}", .{n});
        const end_name = try std.fmt.allocPrint(self.arena, "end{d}", .{n});

        const cond = try self.emitExpr(i.cond);
        try self.line("br i1 {s}, label %{s}, label %{s}", .{ cond, then_name, if (i.else_stmt != null) else_name else end_name });
        self.terminated = true;

        try self.label(then_name);
        try self.emitStmt(i.then_block);
        try self.branchTo(end_name);

        if (i.else_stmt) |e| {
            try self.label(else_name);
            try self.emitStmt(e);
            try self.branchTo(end_name);
        }

        try self.label(end_name);
    }

    // ------------------------------------------------------------ expressions

    /// Emits the instructions for `e` and returns the LLVM value holding its
    /// result: a constant like "42" or a register like "%t3".
    fn emitExpr(self: *CodeGen, e: *const Expr) Error![]const u8 {
        switch (e.data) {
            .int => |v| return std.fmt.allocPrint(self.arena, "{d}", .{v}),
            .bool => |v| return if (v) "true" else "false",
            .ident => |id| {
                const r = try self.tmp();
                try self.line("{s} = load {s}, ptr {s}", .{ r, llvmType(e.type), self.slots.get(id.decl.?).? });
                return r;
            },
            .unary => |u| {
                if (u.op == .star) {
                    // *p: load through the pointer p holds.
                    const p = try self.emitExpr(u.operand);
                    const r = try self.tmp();
                    try self.line("{s} = load {s}, ptr {s}", .{ r, llvmType(e.type), p });
                    return r;
                }
                if (u.op == .amp) {
                    // &x is simply the address of x's stack slot.
                    if (u.operand.data == .ident) return self.slots.get(u.operand.data.ident.decl.?).?;
                    // &*p is p itself: same address, no copy.
                    switch (u.operand.data) {
                        .unary => |inner| if (inner.op == .star) return self.emitExpr(inner.operand),
                        else => {},
                    }
                    // &(temporary): give the value a slot of its own.
                    const v = try self.emitExpr(u.operand);
                    const slot = try std.fmt.allocPrint(self.arena, "%ref{d}", .{self.next_tmp});
                    self.next_tmp += 1;
                    const ty = llvmType(u.operand.type);
                    try self.allocas.writer.print("  {s} = alloca {s}\n", .{ slot, ty });
                    try self.line("store {s} {s}, ptr {s}", .{ ty, v, slot });
                    return slot;
                }
                const v = try self.emitExpr(u.operand); // unary minus
                const r = try self.tmp();
                try self.line("{s} = sub i64 0, {s}", .{ r, v });
                return r;
            },
            .binary => |b| {
                const l = try self.emitExpr(b.lhs);
                const rr = try self.emitExpr(b.rhs);
                const r = try self.tmp();
                const arith: ?[]const u8 = switch (b.op) {
                    .plus => "add",
                    .minus => "sub",
                    .star => "mul",
                    .slash => "sdiv",
                    else => null,
                };
                if (arith) |op| {
                    try self.line("{s} = {s} i64 {s}, {s}", .{ r, op, l, rr });
                } else {
                    const pred: []const u8 = switch (b.op) {
                        .eq_eq => "eq",
                        .not_eq => "ne",
                        .less => "slt", // s = signed
                        .less_eq => "sle",
                        .greater => "sgt",
                        .greater_eq => "sge",
                        else => unreachable,
                    };
                    try self.line("{s} = icmp {s} {s} {s}, {s}", .{ r, pred, llvmType(b.lhs.type), l, rr });
                }
                return r;
            },
            .call => |c| {
                var args: std.Io.Writer.Allocating = .init(self.arena);
                for (c.args, 0..) |arg, i| {
                    const v = try self.emitExpr(arg); // left to right
                    if (i > 0) try args.writer.writeAll(", ");
                    try args.writer.print("{s} {s}", .{ llvmType(arg.type), v });
                }
                const ret = c.func.?.ret_type;
                if (ret.* == .void) {
                    try self.line("call void @flint.{s}({s})", .{ c.name, args.written() });
                    return ""; // no value; the checker makes sure nobody uses it
                }
                const r = try self.tmp();
                try self.line("{s} = call {s} @flint.{s}({s})", .{ r, llvmType(ret), c.name, args.written() });
                return r;
            },
        }
    }
};
