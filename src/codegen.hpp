#pragma once
#include "ast.hpp"
#include "types.hpp"
#include <cstdint>
#include <span>
#include <string>
#include <unordered_map>

// Emits textual LLVM IR. Every Flint function becomes
//     define i64 @flint.<name>()
// and a small C-compatible @main calls @flint.main and returns its
// result as the process exit code.
//
// Each variable gets a stack slot (alloca). Reads are loads, writes are
// stores. That is slow-looking IR, but LLVM's mem2reg pass turns the
// slots into registers, so -O2 output is as tight as hand-written code.
class CodeGen {
public:
  std::string run(std::span<FnDecl *> fns) {
    std::string out = "; generated by flint\n\n";
    const FnDecl *main_fn = nullptr;
    for (FnDecl *fn : fns) {
      out += emit_fn(fn);
      if (fn->name == "main")
        main_fn = fn;
    }

    // The C entry point. `fn main()` exits with 0; `fn main() -> i64`
    // exits with its result.
    out += "define i32 @main() {\nentry:\n";
    if (main_fn->ret_type->kind == TypeKind::Void) {
      out += "  call void @flint.main()\n  ret i32 0\n";
    } else {
      out += "  %r = call i64 @flint.main()\n"
             "  %code = trunc i64 %r to i32\n"
             "  ret i32 %code\n";
    }
    out += "}\n";
    return out;
  }

private:
  std::string allocas_; // stack slots, placed at the top of the entry block
  std::string body_;    // all other instructions
  const Type *ret_type_ = nullptr; // return type of the function being emitted
  int next_tmp_ = 0;
  int next_label_ = 0;
  bool terminated_ = false; // current block already ended with `ret`
  std::unordered_map<const VarStmt *, std::string>
      slots_; // variable → its alloca

  // ------------------------------------------------------------ helpers

  static std::string llvm_type(const Type *t) {
    switch (t->kind) {
    case TypeKind::Void:
      return "void";
    case TypeKind::Bool:
      return "i1";
    case TypeKind::Ref:
      return "ptr";
    default:
      return "i64";
    }
  }

  // %r = icmp <pred> <type> %l, %rr
  void cmp(const std::string &r, const char *pred, BinaryExpr *b,
           const std::string &l, const std::string &rr) {
    line(r + " = icmp " + pred + " " + llvm_type(b->lhs->type) + " " + l +
         ", " + rr);
  }

  std::string tmp() { return "%t" + std::to_string(next_tmp_++); }

  void line(const std::string &s) { body_ += "  " + s + "\n"; }

  // Starts a new basic block. The previous block must already have ended
  // with a terminator (br or ret).
  void label(const std::string &name) {
    body_ += name + ":\n";
    terminated_ = false;
  }

  // Ends the current block with a jump, unless it already returned.
  void branch_to(const std::string &name) {
    if (!terminated_)
      line("br label %" + name);
    terminated_ = true;
  }

  // ------------------------------------------------------------ functions

  std::string emit_fn(FnDecl *fn) {
    allocas_.clear();
    body_.clear();
    slots_.clear();
    next_tmp_ = 0;
    next_label_ = 0;
    terminated_ = false;
    ret_type_ = fn->ret_type;

    // Parameters arrive as values (%a.arg). Copy each into a stack slot
    // so the body can treat it exactly like a local variable.
    std::string params;
    for (VarStmt *p : fn->params) {
      const std::string ty = llvm_type(p->type);
      const std::string arg = "%" + std::string(p->name) + ".arg";
      const std::string slot =
          "%" + std::string(p->name) + "." + std::to_string(slots_.size());
      slots_[p] = slot;
      if (!params.empty())
        params += ", ";
      params += ty + " " + arg;
      allocas_ += "  " + slot + " = alloca " + ty + "\n";
      line("store " + ty + " " + arg + ", ptr " + slot);
    }

    emit_stmt(fn->body);
    if (!terminated_) {
      // A void function may fall off the end. A function with a return
      // type can't (the checker guarantees it), so the end is unreachable.
      line(ret_type_->kind == TypeKind::Void ? "ret void" : "unreachable");
    }

    return "define " + llvm_type(ret_type_) + " @flint." +
           std::string(fn->name) + "(" + params + ") {\n" + "entry:\n" +
           allocas_ + body_ + "}\n\n";
  }

  // ------------------------------------------------------------ statements

  void emit_stmt(Stmt *s) {
    if (terminated_) {
      // Code after `return` is unreachable, but LLVM still needs every
      // instruction to live in a block. Open a fresh (dead) one.
      body_ += "dead" + std::to_string(next_label_++) + ":\n";
      terminated_ = false;
    }

    switch (s->kind) {
    case StmtKind::Var: {
      auto *v = cast<VarStmt>(s);
      // Unique slot name: shadowed variables share a Flint name.
      const std::string slot =
          "%" + std::string(v->name) + "." + std::to_string(slots_.size());
      slots_[v] = slot;
      const std::string ty = llvm_type(v->type);
      allocas_ += "  " + slot + " = alloca " + ty + "\n";
      line("store " + ty + " " + emit_expr(v->init) + ", ptr " + slot);
      break;
    }
    case StmtKind::Assign: {
      auto *a = cast<AssignStmt>(s);
      auto *target = cast<IdentExpr>(a->target); // checker guarantees an Ident
      line("store " + llvm_type(target->type) + " " + emit_expr(a->value) +
           ", ptr " + slots_.at(target->decl));
      break;
    }
    case StmtKind::Return: {
      auto *r = cast<ReturnStmt>(s);
      if (r->value) {
        const std::string v = emit_expr(r->value);
        line("ret " + llvm_type(ret_type_) + " " + v);
      } else {
        line("ret void");
      }
      terminated_ = true;
      break;
    }
    case StmtKind::Expr:
      emit_expr(cast<ExprStmt>(s)->expr); // result unused
      break;
    case StmtKind::For:
      emit_for(cast<ForStmt>(s));
      break;
    case StmtKind::If:
      emit_if(cast<IfStmt>(s));
      break;
    case StmtKind::Block:
      for (Stmt *child : cast<BlockStmt>(s)->stmts)
        emit_stmt(child);
      break;
    }
  }

  //           br %condN
  //   condN:  %c = ...
  //           br i1 %c, %bodyN, %endN
  //   bodyN:  ...
  //           br %condN          ← jump back: this is the loop
  //   endN:   (code after the loop)
  void emit_for(ForStmt *f) {
    const std::string n = std::to_string(next_label_++);
    const std::string cond_name = "cond" + n;
    const std::string body_name = "body" + n;
    const std::string end_name = "end" + n;

    branch_to(cond_name);

    label(cond_name);
    const std::string cond = emit_expr(f->cond);
    line("br i1 " + cond + ", label %" + body_name + ", label %" + end_name);
    terminated_ = true;

    label(body_name);
    emit_stmt(f->body);
    branch_to(cond_name);

    label(end_name);
  }

  //   entry:  %c = ...                    thenN:  ...
  //           br i1 %c, %thenN, %elseN            br %endN
  //                                       elseN:  ...
  //                                               br %endN
  //                                       endN:   (code after the if)
  void emit_if(IfStmt *i) {
    const std::string n = std::to_string(next_label_++);
    const std::string then_name = "then" + n;
    const std::string else_name = "else" + n;
    const std::string end_name = "end" + n;

    const std::string cond = emit_expr(i->cond);
    line("br i1 " + cond + ", label %" + then_name + ", label %" +
         (i->else_stmt ? else_name : end_name));
    terminated_ = true;

    label(then_name);
    emit_stmt(i->then_block);
    branch_to(end_name);

    if (i->else_stmt) {
      label(else_name);
      emit_stmt(i->else_stmt);
      branch_to(end_name);
    }

    label(end_name);
  }

  // ------------------------------------------------------------ expressions

  // Emits the instructions for `e` and returns the LLVM value holding
  // its result: a constant like "42" or a register like "%t3".
  std::string emit_expr(Expr *e) {
    switch (e->kind) {
    case ExprKind::Int:
      return std::to_string(cast<IntExpr>(e)->value);

    case ExprKind::Bool:
      return cast<BoolExpr>(e)->value ? "true" : "false";
    case ExprKind::Ident: {
      auto *id = cast<IdentExpr>(e);
      const std::string r = tmp();
      line(r + " = load " + llvm_type(id->type) + ", ptr " +
           slots_.at(id->decl));
      return r;
    }

    case ExprKind::Unary: {
      auto *u = cast<UnaryExpr>(e);
      if (u->op == TokenKind::Amp) {
        // &x is simply the address of x's stack slot.
        if (u->operand->kind == ExprKind::Ident) {
          return slots_.at(cast<IdentExpr>(u->operand)->decl);
        }
        // &(temporary): give the value a slot of its own.
        const std::string v = emit_expr(u->operand);
        const std::string slot = "%ref" + std::to_string(next_tmp_++);
        const std::string ty = llvm_type(u->operand->type);
        allocas_ += "  " + slot + " = alloca " + ty + "\n";
        line("store " + ty + " " + v + ", ptr " + slot);
        return slot;
      }
      const std::string v = emit_expr(u->operand); // unary minus
      const std::string r = tmp();
      line(r + " = sub i64 0, " + v);
      return r;
    }

    case ExprKind::Binary: {
      auto *b = cast<BinaryExpr>(e);
      const std::string l = emit_expr(b->lhs);
      const std::string rr = emit_expr(b->rhs);
      const std::string r = tmp();
      switch (b->op) {
      case TokenKind::Plus:
        line(r + " = add i64 " + l + ", " + rr);
        break;
      case TokenKind::Minus:
        line(r + " = sub i64 " + l + ", " + rr);
        break;
      case TokenKind::Star:
        line(r + " = mul i64 " + l + ", " + rr);
        break;
      case TokenKind::Slash:
        line(r + " = sdiv i64 " + l + ", " + rr);
        break;
      case TokenKind::EqEq:
        cmp(r, "eq", b, l, rr);
        break;
      case TokenKind::NotEq:
        cmp(r, "ne", b, l, rr);
        break;
      case TokenKind::Less:
        cmp(r, "slt", b, l, rr);
        break; // s = signed
      case TokenKind::LessEq:
        cmp(r, "sle", b, l, rr);
        break;
      case TokenKind::Greater:
        cmp(r, "sgt", b, l, rr);
        break;
      case TokenKind::GreaterEq:
        cmp(r, "sge", b, l, rr);
        break;
      default:
        break;
      }
      return r;
    }
    case ExprKind::Call: {
      auto *c = cast<CallExpr>(e);
      std::string args;
      for (Expr *arg : c->args) {
        const std::string v = emit_expr(arg); // left to right
        if (!args.empty())
          args += ", ";
        args += llvm_type(arg->type) + " " + v;
      }
      const std::string callee =
          "@flint." + std::string(c->name) + "(" + args + ")";
      if (c->fn->ret_type->kind == TypeKind::Void) {
        line("call void " + callee);
        return ""; // no value; the checker makes sure nobody uses it
      }
      const std::string r = tmp();
      line(r + " = call " + llvm_type(c->fn->ret_type) + " " + callee);
      return r;
    }
    }
    return "0";
  }
};
