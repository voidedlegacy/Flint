#pragma once
#include "ast.hpp"
#include "types.hpp"
#include <cstdint>
#include <span>
#include <string>
#include <unordered_map>

// Emits textual LLVM IR. Every Flint function becomes
//     define i64 @flint.<name>()
// and a small C-compatible @main calls @flint.main and returns its
// result as the process exit code.
//
// Each variable gets a stack slot (alloca). Reads are loads, writes are
// stores. That is slow-looking IR, but LLVM's mem2reg pass turns the
// slots into registers, so -O2 output is as tight as hand-written code.
class CodeGen {
public:
  std::string run(std::span<FnDecl *> fns) {
    std::string out = "; generated by flint\n\n";
    for (FnDecl *fn : fns)
      out += emit_fn(fn);
    out += "define i32 @main() {\n"
           "entry:\n"
           "  %r = call i64 @flint.main()\n"
           "  %code = trunc i64 %r to i32\n"
           "  ret i32 %code\n"
           "}\n";
    return out;
  }

private:
  std::string allocas_; // stack slots, placed at the top of the entry block
  std::string body_;    // all other instructions
  int next_tmp_ = 0;
  int next_label_ = 0;
  bool terminated_ = false; // current block already ended with `ret`
  std::unordered_map<const VarStmt *, std::string>
      slots_; // variable → its alloca

  // ------------------------------------------------------------ helpers

  static std::string llvm_type(const Type *t) {
    switch (t->kind) {
    case TypeKind::Bool:
      return "i1";
    case TypeKind::Ref:
      return "ptr";
    default:
      return "i64";
    }
  }

  std::string tmp() { return "%t" + std::to_string(next_tmp_++); }

  void line(const std::string &s) { body_ += "  " + s + "\n"; }

  // Starts a new basic block. The previous block must already have ended
  // with a terminator (br or ret).
  void label(const std::string &name) {
    body_ += name + ":\n";
    terminated_ = false;
  }

  // Ends the current block with a jump, unless it already returned.
  void branch_to(const std::string &name) {
    if (!terminated_)
      line("br label %" + name);
    terminated_ = true;
  }

  // ------------------------------------------------------------ functions

  std::string emit_fn(FnDecl *fn) {
    allocas_.clear();
    body_.clear();
    slots_.clear();
    next_tmp_ = 0;
    next_label_ = 0;
    terminated_ = false;

    emit_stmt(fn->body);
    if (!terminated_)
      line("ret i64 0"); // falling off the end returns 0

    return "define i64 @flint." + std::string(fn->name) + "() {\n" +
           "entry:\n" + allocas_ + body_ + "}\n\n";
  }

  // ------------------------------------------------------------ statements

  void emit_stmt(Stmt *s) {
    if (terminated_) {
      // Code after `return` is unreachable, but LLVM still needs every
      // instruction to live in a block. Open a fresh (dead) one.
      body_ += "dead" + std::to_string(next_label_++) + ":\n";
      terminated_ = false;
    }

    switch (s->kind) {
    case StmtKind::Var: {
      auto *v = cast<VarStmt>(s);
      // Unique slot name: shadowed variables share a Flint name.
      const std::string slot =
          "%" + std::string(v->name) + "." + std::to_string(slots_.size());
      slots_[v] = slot;
      const std::string ty = llvm_type(v->type);
      allocas_ += "  " + slot + " = alloca " + ty + "\n";
      line("store " + ty + " " + emit_expr(v->init) + ", ptr " + slot);
      break;
    }
    case StmtKind::Assign: {
      auto *a = cast<AssignStmt>(s);
      auto *target = cast<IdentExpr>(a->target); // checker guarantees an Ident
      line("store " + llvm_type(target->type) + " " + emit_expr(a->value) +
           ", ptr " + slots_.at(target->decl));
      break;
    }
    case StmtKind::Return: {
      auto *r = cast<ReturnStmt>(s);
      line("ret i64 " + (r->value ? emit_expr(r->value) : std::string("0")));
      terminated_ = true;
      break;
    }
    case StmtKind::Expr:
      emit_expr(cast<ExprStmt>(s)->expr); // result unused
      break;
    case StmtKind::If:
      emit_if(cast<IfStmt>(s));
      break;
    case StmtKind::Block:
      for (Stmt *child : cast<BlockStmt>(s)->stmts)
        emit_stmt(child);
      break;
    }
  }

  //   entry:  %c = ...                    thenN:  ...
  //           br i1 %c, %thenN, %elseN            br %endN
  //                                       elseN:  ...
  //                                               br %endN
  //                                       endN:   (code after the if)
  void emit_if(IfStmt *i) {
    const std::string n = std::to_string(next_label_++);
    const std::string then_name = "then" + n;
    const std::string else_name = "else" + n;
    const std::string end_name = "end" + n;

    const std::string cond = emit_expr(i->cond);
    line("br i1 " + cond + ", label %" + then_name + ", label %" +
         (i->else_stmt ? else_name : end_name));
    terminated_ = true;

    label(then_name);
    emit_stmt(i->then_block);
    branch_to(end_name);

    if (i->else_stmt) {
      label(else_name);
      emit_stmt(i->else_stmt);
      branch_to(end_name);
    }

    label(end_name);
  }

  // ------------------------------------------------------------ expressions

  // Emits the instructions for `e` and returns the LLVM value holding
  // its result: a constant like "42" or a register like "%t3".
  std::string emit_expr(Expr *e) {
    switch (e->kind) {
    case ExprKind::Int:
      return std::to_string(cast<IntExpr>(e)->value);

    case ExprKind::Ident: {
      auto *id = cast<IdentExpr>(e);
      const std::string r = tmp();
      line(r + " = load " + llvm_type(id->type) + ", ptr " +
           slots_.at(id->decl));
      return r;
    }

    case ExprKind::Unary: {
      auto *u = cast<UnaryExpr>(e);
      if (u->op == TokenKind::Amp) {
        // &x is simply the address of x's stack slot.
        if (u->operand->kind == ExprKind::Ident) {
          return slots_.at(cast<IdentExpr>(u->operand)->decl);
        }
        // &(temporary): give the value a slot of its own.
        const std::string v = emit_expr(u->operand);
        const std::string slot = "%ref" + std::to_string(next_tmp_++);
        const std::string ty = llvm_type(u->operand->type);
        allocas_ += "  " + slot + " = alloca " + ty + "\n";
        line("store " + ty + " " + v + ", ptr " + slot);
        return slot;
      }
      const std::string v = emit_expr(u->operand); // unary minus
      const std::string r = tmp();
      line(r + " = sub i64 0, " + v);
      return r;
    }

    case ExprKind::Binary: {
      auto *b = cast<BinaryExpr>(e);
      const std::string l = emit_expr(b->lhs);
      const std::string rr = emit_expr(b->rhs);
      const std::string r = tmp();
      switch (b->op) {
      case TokenKind::Plus:
        line(r + " = add i64 " + l + ", " + rr);
        break;
      case TokenKind::Minus:
        line(r + " = sub i64 " + l + ", " + rr);
        break;
      case TokenKind::Star:
        line(r + " = mul i64 " + l + ", " + rr);
        break;
      case TokenKind::Slash:
        line(r + " = sdiv i64 " + l + ", " + rr);
        break;
      case TokenKind::EqEq:
        line(r + " = icmp eq " + llvm_type(b->lhs->type) + " " + l + ", " + rr);
        break;
      default:
        break;
      }
      return r;
    }
    }
    return "0";
  }
};
